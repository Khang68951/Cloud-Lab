/**
 * Content (tracks/modules) refers to icons by name so it stays plain data.
 * Only icons listed here are bundled; unknown names fall back to a book.
 * New track needs a new icon? Add it to this map.
 */
const ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  book: BookOpen,
  cloud: Cloud,
  container: Container,
  cpu: Cpu,
  database: Database,
  'file-code': FileCode,
  globe: Globe,
  'graduation-cap': GraduationCap,
  'hard-drive': HardDrive,
  'key-round': KeyRound,
  mail: Mail,
  network: Network,
  'piggy-bank': PiggyBank,
  'shield-check': ShieldCheck,
  split: Split,
  trophy: Trophy,
  zap: Zap,
  workflow: Workflow,
  'git-branch': GitBranch,
  'chart-column': ChartColumn,
  fingerprint: Fingerprint,
  lock: Lock,
  shield: Shield,
  radar: Radar,
  route: Route,
  server: Server,
  gauge: Gauge,
  function: SquareFunction,
  table: Table,
  'door-open': DoorOpen,
  layers: Layers,
  'life-buoy': LifeBuoy,
  'refresh-cw': RefreshCw,
  receipt: Receipt,
  scissors: Scissors,
  tags: Tags,
  rocket: Rocket,
  building: Building,
  archive: Archive,
  waves: Waves,
  brain: Brain,
  compass: Compass,
};

export function ContentIcon({ name, ...props }: { name: string } & LucideProps) {
  const Icon = ICONS[name] ?? BookOpen;
  return <Icon aria-hidden {...props} />;
}
